export const COUNTRIES: CountryRow[] = RAW.map(toRow);

export const BY_NAME: ReadonlyMap<string, CountryRow> = new Map(
  COUNTRIES.map((row) => [row.name, row]),
);

export function countryValue(row: CountryRow, metric: MetricId): number | null {
  return row[metric];
}
